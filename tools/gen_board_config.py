#!/usr/bin/env python3
"""Generate main/board_config.h from a boards/<name>/board-config.yaml.

Usage: gen_board_config.py <board-config.yaml> <output.h>

Keeps the core/board split honest: core code includes board_config.h and never
contains board-specific values. Requires PyYAML (bundled with the ESP-IDF
python environment).
"""

import sys

try:
    import yaml
except ImportError:
    sys.exit("gen_board_config.py: PyYAML is required (pip install pyyaml, "
             "or run inside the ESP-IDF environment)")

CURVES = {"linear": 0, "logarithmic": 1}


def die(msg):
    sys.exit(f"gen_board_config.py: {msg}")


def require(cfg, path):
    node = cfg
    for key in path.split("."):
        if not isinstance(node, dict) or key not in node:
            die(f"missing required key '{path}'")
        node = node[key]
    return node


def main():
    if len(sys.argv) != 3:
        die("usage: gen_board_config.py <board-config.yaml> <output.h>")
    src, dst = sys.argv[1], sys.argv[2]

    with open(src) as f:
        cfg = yaml.safe_load(f)

    board_name = require(cfg, "board_name")
    hostname_prefix = require(cfg, "hostname_prefix")

    gpio_keys = [
        "fan_rocker_up", "fan_rocker_down",
        "light_rocker_up", "light_rocker_down",
        "mua_relay", "dimmer_bridge_tx", "dimmer_bridge_rx",
    ]
    gpio = {k: int(require(cfg, f"gpio.{k}")) for k in gpio_keys}

    fan_curve = require(cfg, "dimmer.fan_curve")
    light_curve = require(cfg, "dimmer.light_curve")
    for name in (fan_curve, light_curve):
        if name not in CURVES:
            die(f"unknown dimmer curve '{name}' (choose from {sorted(CURVES)})")

    lines = [
        "/* Generated by tools/gen_board_config.py from",
        f" * {src}",
        " * DO NOT EDIT — edit the YAML and rebuild. */",
        "#pragma once",
        "",
        f'#define BOARD_NAME "{board_name}"',
        f'#define BOARD_HOSTNAME_PREFIX "{hostname_prefix}"',
        "",
    ]
    for k, v in gpio.items():
        lines.append(f"#define BOARD_GPIO_{k.upper()} {v}")
    lines += [
        "",
        f"#define BOARD_FAN_CURVE {CURVES[fan_curve]} /* {fan_curve} */",
        f"#define BOARD_FAN_MIN_PERCENT {int(require(cfg, 'dimmer.fan_min_percent'))}",
        f"#define BOARD_LIGHT_CURVE {CURVES[light_curve]} /* {light_curve} */",
        f"#define BOARD_FAN_RAMP_MS_PER_PERCENT {int(require(cfg, 'dimmer.fan_ramp_ms_per_percent'))}",
        f"#define BOARD_LIGHT_FADE_MS_PER_PERCENT {int(require(cfg, 'dimmer.light_fade_ms_per_percent'))}",
        "",
        f"#define BOARD_MUA_PRESENT {1 if require(cfg, 'mua.present') else 0}",
        f"#define BOARD_MUA_THRESHOLD_DEFAULT {int(require(cfg, 'mua.threshold_percent_default'))}",
        f"#define BOARD_MUA_HYSTERESIS {int(require(cfg, 'mua.hysteresis_percent'))}",
        "",
        f"#define BOARD_INPUT_DEBOUNCE_MS {int(require(cfg, 'input.debounce_ms'))}",
        f"#define BOARD_INPUT_HOLD_MS {int(require(cfg, 'input.hold_ms'))}",
        f"#define BOARD_INPUT_FACTORY_RESET_HOLD_MS {int(require(cfg, 'input.factory_reset_hold_ms'))}",
        "",
    ]

    with open(dst, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
